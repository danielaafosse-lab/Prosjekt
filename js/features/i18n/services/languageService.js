/**
 * Language Service Class
 */
class LanguageService {
  constructor() {
    this.currentLanguage = localStorage.getItem('econsim_language') || 'no';
    this.translations = translations;
    this.observers = [];
  }

  initialize() {
    console.log(`🌐 Språk: ${this.currentLanguage === 'no' ? 'Norsk' : 'English'}`);
    this.updatePageLanguage();
    return this;
  }

  getLanguage() {
    return this.currentLanguage;
  }

  setLanguage(lang) {
    if (lang !== 'no' && lang !== 'en') lang = 'no';
    this.currentLanguage = lang;
    localStorage.setItem('econsim_language', lang);
    document.documentElement.lang = lang === 'no' ? 'no' : 'en';
    this.updatePageLanguage();
    this.notifyObservers();
    console.log(`🌐 Språk: ${lang === 'no' ? 'Norsk' : 'English'}`);
  }

  t(key, params = {}) {
    const translation = this.translations[this.currentLanguage]?.[key] 
                       || this.translations['no']?.[key] 
                       || key;
    return translation.replace(/\{(\w+)\}/g, (match, param) => 
      params[param] !== undefined ? params[param] : match
    );
  }

  updatePageLanguage() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = this.t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = this.t(el.getAttribute('data-i18n-title'));
    });
    document.querySelectorAll('[data-i18n-tooltip]').forEach(el => {
      el.setAttribute('data-tooltip', this.t(el.getAttribute('data-i18n-tooltip')));
    });
    this.updateLanguageButtons();
  }

  updateLanguageButtons() {
    const noBtn = document.getElementById('langNo');
    const enBtn = document.getElementById('langEn');
    if (noBtn && enBtn) {
      if (this.currentLanguage === 'no') {
        noBtn.classList.add('ring-2', 'ring-blue-500', 'ring-offset-2');
        enBtn.classList.remove('ring-2', 'ring-blue-500', 'ring-offset-2');
      } else {
        enBtn.classList.add('ring-2', 'ring-blue-500', 'ring-offset-2');
        noBtn.classList.remove('ring-2', 'ring-blue-500', 'ring-offset-2');
      }
    }
  }

  addObserver(callback) { this.observers.push(callback); }
  removeObserver(callback) { this.observers = this.observers.filter(o => o !== callback); }
  notifyObservers() { this.observers.forEach(cb => { try { cb(this.currentLanguage); } catch(e) {} }); }
}

const languageService = new LanguageService();
window.languageTranslations = translations;
window.languageService = languageService;
window.setLanguage = (lang) => languageService.setLanguage(lang);

export { languageService, translations };
export default languageService;
